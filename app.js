// Variables
let name = "Ankush";
let age = 22;

// Function
function introduce() {
    console.log("Hello, my name is " + name);
    console.log("I am " + age + " years old.");
}

// Call the function
introduce();

// Condition
if (age >= 18) {
    console.log("You are an adult.");
} else {
    console.log("You are a minor.");
}

// Loop
for (let i = 1; i <= 5; i++) {
    console.log(i);
}
